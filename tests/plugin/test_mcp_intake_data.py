"""
Regression tests for the generated MCP intake question table:
``arckit-mcp/arckit_mcp/intake.py`` (regenerated by ``scripts/generate-mcp-intake.py``).

The mcp-server task ships a second, *machine-readable* intake question table
with the same shape as ``gates_data.py`` (generated by
``scripts/generate-mcp-gates.py``). The test does not execute the mcp-server
package; it runs the standalone generator script against the templates and
asserts:

1. The generated file is valid Python.
2. ``INTAKE`` is a ``dict[str, dict]`` whose values carry the exact keys
   ``questions`` / ``mandatory_inputs`` / ``source`` and the right types.
3. Every ``mandatory_inputs`` entry is a doc-type code in ``COVERAGE``.
4. ``COVERAGE`` covers every doc-type code known to the flat-tree
   ``doc-types.mjs`` (the "20+ known doc-type codes" guarantee from the
   mcp-server task).
5. The parser notes list (``PARSER_NOTES`` comment block) is a list of
   ``str``.

The test imports the generator module by path (no mcp-server dependency), so
it works from a bare arc-kit checkout without the mcp-server installed.
"""

import importlib.util
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / "scripts" / "generate-mcp-intake.py"


@pytest.fixture(scope="module")
def generated():
    """Run the generator once per test module and return the parsed data."""
    with tempfile.TemporaryDirectory(prefix="mcp-intake-test-") as tmp:
        out_path = Path(tmp) / "intake_data.py"
        result = subprocess.run(
            [sys.executable, str(SCRIPT), str(out_path)],
            capture_output=True, text=True, cwd=REPO_ROOT,
        )
        assert result.returncode == 0, (
            f"generate-mcp-intake.py failed (rc={result.returncode}):\n"
            f"stdout: {result.stdout}\nstderr: {result.stderr}"
        )
        assert out_path.is_file(), "generator did not write the output file"
        spec = importlib.util.spec_from_file_location("intake_data_under_test", out_path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module


def test_intake_shape(generated):
    """INTAKE is a dict whose values carry the exact documented keys."""
    intake = generated.INTAKE
    assert isinstance(intake, dict), "INTAKE must be a dict"
    assert intake, "INTAKE must be non-empty (at least one doc type has questions)"
    for code, entry in intake.items():
        assert isinstance(code, str), f"INTAKE key {code!r} is not a str"
        assert isinstance(entry, dict), f"INTAKE[{code!r}] is not a dict"
        assert set(entry.keys()) == {"questions", "mandatory_inputs", "source"}, (
            f"INTAKE[{code!r}] has keys {sorted(entry.keys())}, "
            "expected {'questions', 'mandatory_inputs', 'source'}"
        )
        assert isinstance(entry["questions"], list), (
            f"INTAKE[{code!r}].questions is not a list"
        )
        for q in entry["questions"]:
            assert isinstance(q, str), f"INTAKE[{code!r}].questions has a non-str entry: {q!r}"
            assert q.strip(), f"INTAKE[{code!r}].questions has a blank entry"
        assert isinstance(entry["mandatory_inputs"], list), (
            f"INTAKE[{code!r}].mandatory_inputs is not a list"
        )
        for m in entry["mandatory_inputs"]:
            assert isinstance(m, str), f"INTAKE[{code!r}].mandatory_inputs has a non-str entry: {m!r}"
        assert isinstance(entry["source"], str), f"INTAKE[{code!r}].source is not a str"


def test_mandatory_inputs_are_known_doc_types(generated):
    """Every mandatory_inputs entry is a doc-type code present in COVERAGE."""
    coverage = generated.COVERAGE
    assert isinstance(coverage, dict), "COVERAGE must be a dict"
    for code, entry in generated.INTAKE.items():
        for m in entry["mandatory_inputs"]:
            assert m in coverage, (
                f"INTAKE[{code!r}].mandatory_inputs references {m!r}, "
                f"which is not a doc-type code in COVERAGE ({len(coverage)} known codes)"
            )


def test_coverage_covers_all_known_doc_types(generated):
    """COVERAGE covers every doc-type code in the flat-tree doc-types.mjs."""
    coverage = generated.COVERAGE
    assert isinstance(coverage, dict), "COVERAGE must be a dict"
    assert len(coverage) >= 20, (
        f"COVERAGE must cover at least 20 doc-type codes (the mcp-server "
        f"'20+ known doc-type codes' guarantee); got {len(coverage)}: {sorted(coverage)}"
    )
    for code, status in coverage.items():
        assert status in ("covered", "no-static-questions"), (
            f"COVERAGE[{code!r}] = {status!r}, expected 'covered' or 'no-static-questions'"
        )


def test_parser_notes_are_strings(generated):
    """The PARSER_NOTES block (if present) is a list of str."""
    notes = getattr(generated, "PARSER_NOTES", None)
    if notes is None:
        # No notes is fine — the generator omits the list when there are none.
        return
    assert isinstance(notes, list), "PARSER_NOTES must be a list"
    for n in notes:
        assert isinstance(n, str), f"PARSER_NOTES has a non-str entry: {n!r}"
        assert n.strip(), "PARSER_NOTES has a blank entry"
