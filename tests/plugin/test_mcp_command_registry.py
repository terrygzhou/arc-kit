"""Parity checks for the generated MCP command registry and gate tiers.

Validates ``arckit_mcp/_registry.py`` (regenerated by
``scripts/generate-mcp-registry.py``) and ``arckit_mcp/gates.py``
(regenerated by ``scripts/generate-mcp-gates.py``) against their source
of truth: ``plugins/arckit-claude/config/doc-types.mjs`` and the
command markdown frontmatter / prerequisite blocks.

Checks:

1. ``_registry`` shape: DOC_TYPES, SUBDIR_MAP, MULTI_INSTANCE_TYPES,
   and KNOWN_TYPES are present and well-formed.
2. Every gate code in GATE_TIERS is a registered doc-type
   (KNOWN_TYPES), with documented out-of-scope exceptions for
   ``HLD``, ``MSBD``, and ``J936`` (used in plugin markdown but not
   registered in doc-types.mjs — gaps tracked in the PR).
3. SUBDIR_MAP keys are a subset of DOC_TYPES.
4. MULTI_INSTANCE_TYPES is a subset of DOC_TYPES.
5. Every GATE_TIERS key references an existing command file under one
   of the four primary plugin dirs.
6. Spot-check known gate mappings for representative commands from
   each of the four primary plugins.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
# arckit-mcp is now a sibling repo; its generated modules are the parity target.
sys.path.insert(0, str(REPO_ROOT.parent / "arckit-mcp"))

from arckit_mcp._registry import (  # noqa: E402
    DOC_TYPES,
    KNOWN_TYPES,
    MULTI_INSTANCE_TYPES,
    SUBDIR_MAP,
)
from arckit_mcp.gates import GATE_TIERS  # noqa: E402

PRIMARY_PLUGINS = ("arckit-claude", "arckit-oaa", "arckit-it4it", "arckit-togaf-adm")
PLUGINS_DIR = REPO_ROOT / "plugins"

# Gate codes that appear in plugin markdown prerequisite blocks but are
# not registered in doc-types.mjs.  These are known out-of-scope source
# gaps (tracked in the PR notes); we allow them as documented exceptions
# rather than blocking the parity test:
#
# - HLD:  arckit-togaf-adm/architecture-board.md (prerequisite block
#         references HLD; doc-types.mjs registers HLDR, not HLD)
# - MSBD: arckit-claude/jsp-936.md:75 ("MSBD (MOD Secure by Design)")
# - J936: arckit-claude/mlops.md:74 ("J936 (JSP 936 AI Assurance)");
#         doc-types.mjs registers JSP936, not the J936 shorthand
_UNREGISTERED_GATE_CODES = {"HLD", "MSBD", "J936"}


def _existing_command_stems() -> dict[str, set[str]]:
    stems: dict[str, set[str]] = {}
    for plugin in PRIMARY_PLUGINS:
        commands_dir = PLUGINS_DIR / plugin / "commands"
        stems[plugin] = (
            {p.stem for p in commands_dir.glob("*.md")} if commands_dir.is_dir() else set()
        )
    return stems


@pytest.fixture(scope="module")
def stems() -> dict[str, set[str]]:
    return _existing_command_stems()


# ---------------------------------------------------------------------------
# 1. Registry shape
# ---------------------------------------------------------------------------


def test_registry_shapes():
    """DOC_TYPES, SUBDIR_MAP, MULTI_INSTANCE_TYPES, KNOWN_TYPES are present
    and well-formed."""
    assert isinstance(DOC_TYPES, dict), "DOC_TYPES is not a dict"
    assert len(DOC_TYPES) > 0, "DOC_TYPES is empty — generator produced nothing"
    for code, entry in DOC_TYPES.items():
        assert isinstance(code, str), f"bad DOC_TYPES key: {code!r}"
        assert isinstance(entry, dict), f"{code}: entry is not a dict"
        assert "name" in entry, f"{code}: missing 'name' field"
        assert "category" in entry, f"{code}: missing 'category' field"

    assert isinstance(SUBDIR_MAP, dict), "SUBDIR_MAP is not a dict"
    for key, val in SUBDIR_MAP.items():
        assert isinstance(key, str) and isinstance(val, str), (
            f"SUBDIR_MAP[{key!r}] = {val!r} is not str -> str"
        )

    assert isinstance(MULTI_INSTANCE_TYPES, set), "MULTI_INSTANCE_TYPES is not a set"
    for code in MULTI_INSTANCE_TYPES:
        assert isinstance(code, str), f"MULTI_INSTANCE_TYPES element not str: {code!r}"

    assert isinstance(KNOWN_TYPES, set), "KNOWN_TYPES is not a set"
    assert KNOWN_TYPES == set(DOC_TYPES.keys()), (
        "KNOWN_TYPES does not match set(DOC_TYPES.keys()) — "
        f"extra in KNOWN_TYPES: {KNOWN_TYPES - set(DOC_TYPES.keys())}, "
        f"missing from KNOWN_TYPES: {set(DOC_TYPES.keys()) - KNOWN_TYPES}"
    )


# ---------------------------------------------------------------------------
# 2. Gate codes must be registered doc-types (with known HLD exception)
# ---------------------------------------------------------------------------


def test_gate_codes_are_known_doc_types():
    """Every gate code in GATE_TIERS is in KNOWN_TYPES, with the
    documented out-of-scope exceptions (HLD, MSBD, J936)."""
    unknown: list[tuple[str, str]] = []
    for command, tiers in GATE_TIERS.items():
        for code in tiers:
            if code not in KNOWN_TYPES and code not in _UNREGISTERED_GATE_CODES:
                unknown.append((command, code))
    assert not unknown, (
        "gate codes that are not registered doc-types "
        f"(and not in the documented exceptions {_UNREGISTERED_GATE_CODES}): {unknown}"
    )


# ---------------------------------------------------------------------------
# 3. SUBDIR_MAP keys ⊆ DOC_TYPES
# ---------------------------------------------------------------------------


def test_subdir_map_keys_are_doc_types():
    """Every SUBDIR_MAP key must be a registered doc-type code."""
    bad_keys = set(SUBDIR_MAP) - set(DOC_TYPES)
    assert not bad_keys, (
        f"SUBDIR_MAP keys not present in DOC_TYPES: {bad_keys}"
    )


# ---------------------------------------------------------------------------
# 4. MULTI_INSTANCE_TYPES ⊆ DOC_TYPES
# ---------------------------------------------------------------------------


def test_multi_instance_types_are_doc_types():
    """Every MULTI_INSTANCE_TYPES member must be a registered doc-type code."""
    bad_codes = MULTI_INSTANCE_TYPES - set(DOC_TYPES)
    assert not bad_codes, (
        f"MULTI_INSTANCE_TYPES members not present in DOC_TYPES: {bad_codes}"
    )


# ---------------------------------------------------------------------------
# 5. GATE_TIERS keys reference existing command files
# ---------------------------------------------------------------------------


def test_gate_tiers_keys_reference_existing_commands(stems):
    """Every GATE_TIERS key maps to an existing command .md file."""
    for key in GATE_TIERS:
        plugin, _, cmd = key.partition("/")
        assert plugin in stems, f"unknown plugin {plugin!r} in key {key!r}"
        assert cmd in stems[plugin], (
            f"{key}: no plugins/{plugin}/commands/{cmd}.md"
        )


# ---------------------------------------------------------------------------
# 6. Spot-check known gate mappings
# ---------------------------------------------------------------------------


def test_known_gate_mappings():
    """Spot-check gate tiers for representative commands from each
    primary plugin to catch regressions where the generator silently
    drops or mis-assigns a tier."""

    # --- arckit-claude/requirements ---
    # requirements.md has no REQ gate: REQ is the output doc-type of the
    # command, not a prerequisite.  Actual tiers: STKE MANDATORY;
    # PRIN, RISK, SOBC RECOMMENDED; PLAN OPTIONAL.
    req = GATE_TIERS.get("arckit-claude/requirements", {})
    assert req.get("STKE") == "MANDATORY", (
        "arckit-claude/requirements: STKE MANDATORY missing"
    )
    assert req.get("PRIN") == "RECOMMENDED", (
        "arckit-claude/requirements: PRIN RECOMMENDED missing"
    )
    assert req.get("RISK") == "RECOMMENDED", (
        "arckit-claude/requirements: RISK RECOMMENDED missing"
    )
    assert req.get("SOBC") == "RECOMMENDED", (
        "arckit-claude/requirements: SOBC RECOMMENDED missing"
    )
    assert req.get("PLAN") == "OPTIONAL", (
        "arckit-claude/requirements: PLAN OPTIONAL missing"
    )

    # --- arckit-oaa (agile strategy, agile governance) ---
    oaa_agile_gov = GATE_TIERS.get("arckit-oaa/agile-governance", {})
    assert "PRIN" in oaa_agile_gov, (
        "arckit-oaa/agile-governance: PRIN gate missing"
    )

    oaa_agile_strat = GATE_TIERS.get("arckit-oaa/agile-strategy", {})
    assert "PRIN" in oaa_agile_strat, (
        "arckit-oaa/agile-strategy: PRIN gate missing"
    )

    # --- arckit-it4it (consume and fulfil) ---
    it4it_cf = GATE_TIERS.get("arckit-it4it/it4it-consume-fulfil", {})
    assert "PRIN" in it4it_cf, (
        "arckit-it4it/it4it-consume-fulfil: PRIN gate missing"
    )

    # --- arckit-togaf-adm (data-architecture, transition-architecture,
    #     gap-analysis, architecture-board) ---
    ta_data = GATE_TIERS.get("arckit-togaf-adm/data-architecture", {})
    assert "APP" in ta_data and ta_data["APP"] == "MANDATORY", (
        "arckit-togaf-adm/data-architecture: APP MANDATORY missing"
    )
    assert "BPCM" in ta_data and ta_data["BPCM"] == "MANDATORY", (
        "arckit-togaf-adm/data-architecture: BPCM MANDATORY missing"
    )

    ta_trans = GATE_TIERS.get("arckit-togaf-adm/transition-architecture", {})
    assert "GAPA" in ta_trans and ta_trans["GAPA"] == "MANDATORY", (
        "arckit-togaf-adm/transition-architecture: GAPA MANDATORY missing"
    )

    ta_gap = GATE_TIERS.get("arckit-togaf-adm/gap-analysis", {})
    assert "BPCM" in ta_gap and ta_gap["BPCM"] == "MANDATORY", (
        "arckit-togaf-adm/gap-analysis: BPCM MANDATORY missing"
    )

    ta_board = GATE_TIERS.get("arckit-togaf-adm/architecture-board", {})
    assert "PRIN" in ta_board and ta_board["PRIN"] == "MANDATORY", (
        "arckit-togaf-adm/architecture-board: PRIN MANDATORY missing"
    )
