"""Parity checks for the generated MCP handoff table.

Validates ``arckit_mcp/handoffs.py`` (regenerated by
``scripts/generate-mcp-handoffs.py``) against the command markdown
frontmatter it was generated from.

Checks:

1. Every ``HANDOFFS`` key references an existing command file under one of
   the four primary plugin dirs.
2. Every handoff target resolves to an existing command file in the same or
   another primary plugin dir.
3. No command lists the same handoff target twice.
4. ``arckit-claude/requirements`` carries the four mandated targets:
   ``data-model``, ``research``, ``risk``, ``dpia``.
"""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
# arckit-mcp is now a sibling repo; its generated modules are the parity target.
sys.path.insert(0, str(REPO_ROOT.parent / "arckit-mcp"))

from arckit_mcp.handoffs import HANDOFFS  # noqa: E402

PRIMARY_PLUGINS = ("arckit-claude", "arckit-oaa", "arckit-it4it", "arckit-togaf-adm")
PLUGINS_DIR = REPO_ROOT / "plugins"


def _existing_command_stems() -> dict[str, set[str]]:
    stems: dict[str, set[str]] = {}
    for plugin in PRIMARY_PLUGINS:
        commands_dir = PLUGINS_DIR / plugin / "commands"
        stems[plugin] = (
            {p.stem for p in commands_dir.glob("*.md")} if commands_dir.is_dir() else set()
        )
    return stems


@pytest.fixture(scope="module")
def stems() -> dict[str, set[str]]:
    return _existing_command_stems()


def test_handoffs_table_shape():
    """HANDOFFS is a dict[str, list[tuple[str, str, str]]] with 3-tuples."""
    assert isinstance(HANDOFFS, dict)
    assert len(HANDOFFS) > 0, "HANDOFFS is empty — generator produced nothing"
    for key, entries in HANDOFFS.items():
        assert isinstance(key, str) and "/" in key, f"bad key shape: {key!r}"
        assert isinstance(entries, list), f"{key}: entries is not a list"
        for entry in entries:
            assert isinstance(entry, tuple) and len(entry) == 3, (
                f"{key}: entry is not a 3-tuple: {entry!r}"
            )
            for field in entry:
                assert isinstance(field, str), (
                    f"{key}: tuple field is not str: {entry!r}"
                )


def test_keys_reference_existing_command_files(stems):
    """Every HANDOFFS key maps to an existing command .md file."""
    for key in HANDOFFS:
        plugin, _, cmd = key.partition("/")
        assert plugin in stems, f"unknown plugin {plugin!r} in key {key!r}"
        assert cmd in stems[plugin], (
            f"{key}: no plugins/{plugin}/commands/{cmd}.md"
        )


def test_targets_resolve_to_existing_commands(stems):
    """Every handoff target is an existing command in some primary plugin."""
    all_stems = set().union(*stems.values())
    missing = [
        (key, entry[0])
        for key, entries in HANDOFFS.items()
        for entry in entries
        if entry[0] not in all_stems
    ]
    assert not missing, (
        f"handoff targets that don't match any existing command file: {missing}"
    )


def test_no_duplicate_targets_within_a_command():
    """A command must not hand off to the same target twice."""
    dups: dict[str, Counter] = {}
    for key, entries in HANDOFFS.items():
        counts = Counter(entry[0] for entry in entries)
        bad = {t: n for t, n in counts.items() if n > 1}
        if bad:
            dups[key] = bad
    assert not dups, f"duplicate handoff targets within a command: {dups}"


def test_requirements_has_all_mandated_targets():
    """arckit-claude/requirements must hand off to data-model, research,
    risk, and dpia."""
    assert "arckit-claude/requirements" in HANDOFFS, (
        "arckit-claude/requirements missing from HANDOFFS entirely"
    )
    targets = {entry[0] for entry in HANDOFFS["arckit-claude/requirements"]}
    required = {"data-model", "research", "risk", "dpia"}
    missing = required - targets
    assert not missing, (
        f"arckit-claude/requirements is missing mandated handoff targets: {missing}"
    )


def test_condition_code_only_when_text_present():
    """condition_code must be non-empty only when condition_text is too."""
    for key, entries in HANDOFFS.items():
        for target, cond_text, cond_code in entries:
            if cond_code:
                assert cond_text, f"{key} -> {target}: code without text"
