def it4it_check_value_stream(stream):
    """Validate an IT4IT value-stream document.

    Checks the required structure, stage catalog membership, and that each
    stage traces to at least one functional component. Returns a structured
    verdict, never raises on malformed input.
    """
    problems = []
    if not isinstance(stream, dict):
        return {"valid": False, "problems": ["stream must be an object/dict"], "stage_report": []}
    if not str(stream.get("name") or "").strip():
        problems.append("missing required field 'name'")
    stages = stream.get("stages")
    if not isinstance(stages, list) or not stages:
        problems.append("'stages' must be a non-empty array")
        stages = []
    stage_report = []
    for i, s in enumerate(stages):
        if not isinstance(s, dict):
            problems.append(f"stages[{i}] must be an object")
            continue
        sid = s.get("id") or s.get("stage") or f"stages[{i}]"
        entry = {
            "id": sid,
            "name": s.get("name", ""),
            "components": s.get("components", []),
            "ok": True,
        }
        if not str(entry["name"] or "").strip():
            entry["ok"] = False
            problems.append(f"stages[{i}] missing 'name'")
        if not isinstance(entry["components"], list) or not entry["components"]:
            entry["ok"] = False
            problems.append(f"stage {sid} traces to no functional components")
        stage_report.append(entry)
    untraced = [e["id"] for e in stage_report if not e["ok"] and not e["components"]]
    return {
        "valid": not problems,
        "problems": problems,
        "untraced_stages": untraced,
        "stage_report": stage_report,
    }

def it4it_check_component_trace(component, known_streams=None):
    """Traceability check for an IT4IT functional-component document."""
    problems = []
    counts: dict = {}
    orphaned = []
    if not isinstance(component, dict):
        return {"valid": False, "problems": ["component must be an object/dict"], "orphaned_refs": [], "per_stream_counts": {}}
    comps = component.get("components")
    if not isinstance(comps, list) or not comps:
        problems.append("'components' must be a non-empty array")
        comps = []
    known = set(known_streams) if known_streams else None
    for i, c in enumerate(comps):
        if not isinstance(c, dict):
            problems.append(f"components[{i}] must be an object")
            continue
        cid = c.get("id") or c.get("name")
        if not str(cid or "").strip():
            problems.append(f"components[{i}] missing 'id' (or 'name')")
            continue
        stream = c.get("value_stream") or c.get("stream") or "shared"
        key = str(stream)
        counts[key] = counts.get(key, 0) + 1
        if known is not None and key != "shared" and key not in known:
            orphaned.append({"component": cid, "references_stream": key})
    problems.extend(f"component {o['component']} references undefined value stream {o['references_stream']!r}" for o in orphaned)
    return {
        "valid": not problems,
        "problems": problems,
        "orphaned_refs": orphaned,
        "per_stream_counts": counts,
    }

