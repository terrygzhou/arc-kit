    principles = canvas.get("design_principles")
    if not isinstance(principles, list) or not principles:
        gaps.append("'design_principles' must be a non-empty array")
    else:
        for i, p in enumerate(principles):
            for field in ("principle", "axiom", "rationale"):
                if not (isinstance(p, dict) and str(p.get(field) or "").strip()):
                    gaps.append(f"design_principles[{i}] missing {field!r}")
    waves = canvas.get("transformation_waves")
    if not isinstance(waves, list) or not waves:
        gaps.append("'transformation_waves' must be a non-empty array")
    else:
        for i, w in enumerate(waves):
            if not (isinstance(w, dict) and w.get("wave") and w.get("duration")):
                gaps.append(f"transformation_waves[{i}] missing 'wave' or 'duration'")
    resilience = canvas.get("resilience_mapping", [])
    if not isinstance(resilience, list):
        gaps.append("'resilience_mapping', when present, must be an array")
    stats = {
        "design_principles": len(principles) if isinstance(principles, list) else 0,
        "transformation_waves": len(waves) if isinstance(waves, list) else 0,
        "resilience_mappings": len(resilience) if isinstance(resilience, list) else 0,
    }
    return {"complete": not gaps, "gaps": gaps, "stats": stats}

